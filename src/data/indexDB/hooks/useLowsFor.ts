import { useLiveQuery } from "dexie-react-hooks"
import db from "../db"
import consoleInfo from "@/utilities/consoleInfo"

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

export default function useLowsFor(symbol = "MISSING") {
  const data = useLiveQuery(async () => {
    const stored = await db.lows.where({ symbol }).first()

    db.lowsCache[symbol] = stored?.data

    consoleInfo(`useLowsFor ${symbol} : stored`)
    return stored?.data
  }, [symbol])

  return data
}

